/// <summary>
/// Categories for items in the inventory system.
/// </summary>
public enum ItemCategory
{
    Weapon,
    Item
}

// ???????????????????????????????????????????????????????????????????
// COMBAT SYSTEM
// ???????????????????????????????????????????????????????????????????

/// <summary>
/// Types of hitboxes used in the combat system.
/// Determines which weapon/body part is dealing damage.
/// </summary>
public enum HitboxType
{
    Fist,
    Foot,
    Katana,
    Nunchaku,
    Staff,
    Shuriken,
    Utility,
    None
}

/// <summary>
/// Types of hit reactions that can be triggered when damage is dealt.
/// Affects animation and damage response behavior.
/// </summary>
public enum HitReactionType
{
    None,
    Light_High,  // Head/Chest snap
    Light_Low,   // Stomach/Leg flinch
    Heavy_Back,  // Stagger backward
    Knockdown,   // Fall to ground
    Launch       // Air combo starter
}

[System.Flags]
public enum AnimationExitEvent
{
    None            = 0,
    ClipEnded       = 1 << 0,
    ClipInterrupted = 1 << 1,
    EndImmobilized  = 1 << 2,
    EndThrow        = 1 << 3,
    BreakClinch     = 1 << 4,
    EndBlock        = 1 << 5,
    EndPickup       = 1 << 6,
    EndAcrobatics   = 1 << 7,
}