using UnityEngine;
using JSAM;

[CreateAssetMenu(fileName = "NewThrow", menuName = "Combat/Throw")]
public class CombatThrow : ScriptableObject
{
    // ?????????????????????????????????????????????
    // VISUALS
    // ?????????????????????????????????????????????

    public string throwName;
    public AnimationClip attackerThrowClip;
    public AnimationClip victimThrowClip;

    // ?????????????????????????????????????????????
    // COMBAT STATS
    // ?????????????????????????????????????????????

    [Header("Combat Stats")]
    public float damage = 20f;

    // ?????????????????????????????????????????????
    // AUDIO
    // ?????????????????????????????????????????????

    [Header("SFX")]
    public AnimationAudioEvent[] audioEvents;

    // ?????????????????????????????????????????????
    // THROW LAUNCH ACTIVATION
    // ?????????????????????????????????????????????

    [Header("Throw Launch Activation (Normalized)")]
    [Tooltip("Choose the time when the throw is launched during the attack animation. 0 if not applicable")]
    [Range(0f, 1f)] public float throwLaunchActivation = 0.5f;

    // ?????????????????????????????????????????????
    // THROW PHYSICS
    // ????????????????????????????????????????????

    [Header("Throw Physics (Meters)")]
    [Range(0f, 5f)] public float throwArcHeight = 1.5f;
    [Range(0f, 10f)] public float throwDistance = 4f;
    public bool flipThrow;

    // ?????????????????????????????????????????????
    // CACHED DATA
    // ?????????????????????????????????????????????

    private float? _cachedAttackerDuration;
    private float? _cachedVictimDuration;

    public float AttackerAnimationDuration
    {
        get
        {
            if (!_cachedAttackerDuration.HasValue && attackerThrowClip != null)
                _cachedAttackerDuration = attackerThrowClip.length;

            return _cachedAttackerDuration ?? 0f;
        }
    }

    public float VictimAnimationDuration
    {
        get
        {
            if (!_cachedVictimDuration.HasValue && victimThrowClip != null)
                _cachedVictimDuration = victimThrowClip.length;

            return _cachedVictimDuration ?? 0f;
        }
    }

#if UNITY_EDITOR
    private void OnValidate()
    {
        if (attackerThrowClip != null && string.IsNullOrEmpty(throwName))
            throwName = attackerThrowClip.name;

        _cachedAttackerDuration = null;
        _cachedVictimDuration = null;

        throwLaunchActivation = Mathf.Clamp01(throwLaunchActivation);

        ResetRuntimeState();
    }

    private void OnEnable()
    {
        ResetRuntimeState();
    }

    private void ResetRuntimeState()
    {
        if (audioEvents != null)
        {
            for (int i = 0; i < audioEvents.Length; i++)
            {
                audioEvents[i].hasPlayed = false;
            }
        }
    }
#endif
}
