using UnityEngine;
using JSAM;

[CreateAssetMenu(fileName = "NewClinchAttack", menuName = "Combat/Clinch Attack")]
public class ClinchAttack : ScriptableObject, IActiveCombatMove
{
    // ?????????????????????????????????????????????
    // VISUALS
    // ?????????????????????????????????????????????

    public string attackName;
    public AnimationClip attackerAttackClip;
    public AnimationClip victimAttackClip;

    // ?????????????????????????????????????????????
    // COMBAT STATS
    // ?????????????????????????????????????????????

    [Header("Combat Stats")]
    public float damage = 10f;
    public HitReactionType reactionToTrigger = HitReactionType.Light_High;

    // ?????????????????????????????????????????????
    // AUDIO
    // ?????????????????????????????????????????????

    [Header("SFX")]
    public AnimationAudioEvent[] audioEvents;

    // ?????????????????????????????????????????????
    // HIT WINDOW
    // ?????????????????????????????????????????????

    [Header("Hitbox Window (Normalized)")]
    [Range(0f, 1f)] public float hitStart = 0.25f;
    [Range(0f, 1f)] public float hitEnd = 0.45f;

    // ?????????????????????????????????????????????
    // COMBO WINDOW
    // ?????????????????????????????????????????????

    [Header("Combo Window (Normalized)")]
    public bool canCombo = true;
    [Range(0f, 1f)] public float comboStart = 0.55f;
    [Range(0f, 1f)] public float comboEnd = 0.85f;

    // ?????????????????????????????????????????????
    // IActiveCombatMove
    // ?????????????????????????????????????????????

    float IActiveCombatMove.Damage => damage;
    HitReactionType IActiveCombatMove.ReactionToTrigger => reactionToTrigger;
    AnimationAudioEvent[] IActiveCombatMove.AudioEvents => audioEvents;

    // ?????????????????????????????????????????????
    // CACHED DATA
    // ?????????????????????????????????????????????

    private float? _cachedAttackerDuration;
    private float? _cachedVictimDuration;

    public float AttackerAnimationDuration
    {
        get
        {
            if (!_cachedAttackerDuration.HasValue && attackerAttackClip != null)
                _cachedAttackerDuration = attackerAttackClip.length;

            return _cachedAttackerDuration ?? 0f;
        }
    }

    public float VictimAnimationDuration
    {
        get
        {
            if (!_cachedVictimDuration.HasValue && victimAttackClip != null)
                _cachedVictimDuration = victimAttackClip.length;

            return _cachedVictimDuration ?? 0f;
        }
    }

    // ?????????????????????????????????????????????
    // WINDOW HELPERS
    // ?????????????????????????????????????????????

    public bool IsInHitWindow(float normalizedTime)
        => normalizedTime >= hitStart && normalizedTime <= hitEnd;

    public bool IsInComboWindow(float normalizedTime)
        => canCombo && normalizedTime >= comboStart && normalizedTime <= comboEnd;

    private void ResetRuntimeState()
    {
        if (audioEvents != null)
        {
            for (int i = 0; i < audioEvents.Length; i++)
            {
                audioEvents[i].hasPlayed = false;
            }
        }
    }

#if UNITY_EDITOR
    private void OnValidate()
    {
        if (attackerAttackClip != null && string.IsNullOrEmpty(attackName))
            attackName = attackerAttackClip.name;

        _cachedAttackerDuration = null;
        _cachedVictimDuration = null;

        hitStart = Mathf.Clamp01(hitStart);
        hitEnd = Mathf.Clamp(hitEnd, hitStart, 1f);

        comboStart = Mathf.Clamp01(comboStart);
        comboEnd = Mathf.Clamp(comboEnd, comboStart, 1f);

        if (!canCombo)
        {
            comboStart = 1f;
            comboEnd = 1f;
        }

        ResetRuntimeState();
    }

    private void OnEnable()
    {
        ResetRuntimeState();
    }
#endif
}
